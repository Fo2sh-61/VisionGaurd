/** Every string the console can say, as a key.
 *
 *  Two vocabularies live here and they are not the same thing:
 *
 *  - `UiKey` is wording the console owns outright. Change it freely; nothing
 *    outside `web/` knows these names.
 *  - `NoteCode` is the **contract with the engine**. Each one must exist in
 *    `engine/vg/api/notes.py`, spelled identically. Renaming one is a
 *    coordinated change on both sides, and `engine/tests/test_notes.py` is
 *    what stops it drifting.
 *
 *  `MessageKey` is the union, and `en.ts` is typed `Record<MessageKey, string>`
 *  so the compiler refuses to build with an English wording missing. That is
 *  the whole completeness proof — there is no separate test for it.
 *
 *  Arabic is deliberately `Partial`: a missing Arabic wording is the designed
 *  state while it is being reviewed, and it falls back to English.
 *
 *  **Never assemble a sentence from several keys.** Pass parameters instead —
 *  `t('attendance.late', { minutes })`, not `t('arrived') + n + t('late')`.
 *  Arabic does not order the parts the way English does, and a sentence glued
 *  together in code cannot be reordered by whoever writes the translation.
 *  P11-FR-001. */

